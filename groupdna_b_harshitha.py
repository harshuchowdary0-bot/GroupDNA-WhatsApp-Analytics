"""### Feature 6 — Response Speed and Silent Streaks
Uses datetime arithmetic for response gaps and checks every day in the 60-day period for silent streaks.
"""

def average_response_gaps(data):
    gaps = {}

    for previous, current in zip(data, data[1:]):
        if current["sender"] == previous["sender"]:
            continue

        seconds = (current["datetime"] - previous["datetime"]).total_seconds()
        person = current["sender"]

        if person not in gaps:
            gaps[person] = []

        gaps[person].append(seconds)

    averages = {}
    for person in PEOPLE_ORDER:
        if person in gaps and gaps[person]:
            averages[person] = sum(gaps[person]) / len(gaps[person])
        else:
            averages[person] = 0

    return averages, gaps

def longest_silent_streak(active_day_set, all_days):
    longest = 0
    current = 0

    for day in all_days:
        if day not in active_day_set:
            current += 1
            if current > longest:
                longest = current
        else:
            current = 0

    return longest

