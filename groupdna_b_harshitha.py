def average_burst_length(data):
    bursts = {person: [] for person in PEOPLE_ORDER}
    previous_sender = None
    current_burst = 0

    for message in data:
        sender = message["sender"]

        if sender == previous_sender:
            current_burst += 1
        else:
            if previous_sender is not None:
                bursts[previous_sender].append(current_burst)
            previous_sender = sender
            current_burst = 1

    if previous_sender is not None:
        bursts[previous_sender].append(current_burst)

    averages = {}
    for person in PEOPLE_ORDER:
        if bursts[person]:
            averages[person] = sum(bursts[person]) / len(bursts[person])
        else:
            averages[person] = 0

    return averages

