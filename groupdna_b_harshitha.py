def looks_like_date_prefix(line):
    """Check DD/MM/YY without using regex."""
    return (
        len(line) >= 8
        and line[2] == "/"
        and line[5] == "/"
        and line[0:2].isdigit()
        and line[3:5].isdigit()
        and line[6:8].isdigit()
    )

def parse_chat_file(file_name):
    """
    Parse a WhatsApp text export.
    User messages are retained, including media/deleted entries with a status.
    System messages are skipped from the message list.
    Continuation lines are appended to the previous message.
    """
    parsed = []
    system_count = 0

    try:
        file_handle = open(file_name, "r", encoding="utf-8")
    except FileNotFoundError:
        file_handle = open("/content/" + file_name, "r", encoding="utf-8")

    with file_handle as f:
        raw_lines = f.readlines()

    for raw in raw_lines:
        line = raw.strip()

        if line == "":
            continue

        if not looks_like_date_prefix(line):
            if parsed:
                parsed[-1]["text"] += " " + line
            continue

        if " - " not in line:
            system_count += 1
            continue

        timestamp, remainder = line.split(" - ", 1)

        if ": " not in remainder:
            system_count += 1
            continue

        sender, text = remainder.split(": ", 1)

        try:
            dt = datetime.strptime(timestamp, "%d/%m/%y, %H:%M")
        except ValueError:
            system_count += 1
            continue

        status = "normal"
        if text == "<Media omitted>":
            status = "media"
        elif text == "This message was deleted":
            status = "deleted"

        parsed.append({
            "timestamp": timestamp,
            "datetime": dt,
            "sender": sender,
            "text": text,
            "status": status
        })

    return parsed, system_count

