def count_caring_keywords(person):
    total = 0
    for message in normal_messages:
        if message["sender"] != person:
            continue
        lower_text = message["text"].lower()
        for keyword in CARING_KEYWORDS:
            total += lower_text.count(keyword)
    return total

def night_message_ratio(person):
    person_messages = [m for m in messages if m["sender"] == person]
    if not person_messages:
        return 0
    night_count = 0
    for message in person_messages:
        hour = message["datetime"].hour
        if hour >= 23 or hour <= 4:
            night_count += 1
    return night_count / len(person_messages)

def average_words(person):
    person_messages = [
        m for m in normal_messages if m["sender"] == person
    ]
    if not person_messages:
        return 0
    return sum(len(m["text"].split()) for m in person_messages) / len(person_messages)

def drama_ratio(person):
    person_messages = [
        m for m in normal_messages if m["sender"] == person
    ]
    if not person_messages:
        return 0

    dramatic = 0
    for message in person_messages:
        text = message["text"]
        if (len(text) >= 3 and text.isupper()) or text.count("!") >= 2:
            dramatic += 1

    return dramatic / len(person_messages)

def comedy_ratio(person):
    person_messages = [
        m for m in normal_messages if m["sender"] == person
    ]
    if not person_messages:
        return 0

    funny_hits = 0
    for message in person_messages:
        lower_text = message["text"].lower()
        for keyword in COMEDY_KEYWORDS:
            funny_hits += lower_text.count(keyword)

    return funny_hits / len(person_messages)

def question_ratio(person):
    person_messages = [
        m for m in normal_messages if m["sender"] == person
    ]
    if not person_messages:
        return 0

    questions = 0
    for message in person_messages:
        if message["text"].rstrip().endswith("?"):
            questions += 1

    return questions / len(person_messages)

